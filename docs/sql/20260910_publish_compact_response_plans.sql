      SELECT 1 FROM w_emergency_response_plan old
      WHERE old.event_type=p.event_type AND old.source_document='compact-20260910');
  UPDATE w_emergency_response_plan p JOIN compact_plan_next n ON n.previous_id=p.id
    SET p.plan_status=2, p.update_time=CURRENT_TIMESTAMP(6) WHERE p.plan_status=1;
