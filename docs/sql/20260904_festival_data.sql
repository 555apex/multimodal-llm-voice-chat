-- 需求2-1/2-3：2026—2028节假日及重大活动交通背景数据。
-- 可重复执行：event_code唯一，正式维护时可按编码更新；不会删除协作者新增记录。
-- 所有DATETIME均按Asia/Shanghai解释。

CREATE TABLE IF NOT EXISTS w_festival_data (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
    event_code VARCHAR(64) NOT NULL COMMENT '稳定事件编码，用于幂等维护',
    event_name VARCHAR(100) NOT NULL COMMENT '节假日或重大活动名称',
    event_type VARCHAR(24) NOT NULL COMMENT 'HOLIDAY/ADJUSTED_WORKDAY/CONCERT/SPORTS_EVENT/OTHER_EVENT',
    event_start_time DATETIME(6) NOT NULL COMMENT '事件或假期实际开始时间（北京时间）',
    event_end_time DATETIME(6) NOT NULL COMMENT '事件或假期实际结束时间（北京时间）',
    impact_start_time DATETIME(6) NOT NULL COMMENT '允许参与交通原因匹配的影响开始时间',
    impact_end_time DATETIME(6) NOT NULL COMMENT '允许参与交通原因匹配的影响结束时间',
    scope_type VARCHAR(16) NOT NULL COMMENT '影响范围：PROVINCE/CITY/ROUTE',
    region_code CHAR(6) NULL COMMENT '城市级活动行政区划代码；全省事件为空',
    region_name VARCHAR(20) NULL COMMENT '城市名称，如福州市',
    affected_route_codes JSON NULL COMMENT '受影响普通国省道编号JSON数组，如["G104","G316"]',
    venue VARCHAR(200) NULL COMMENT '重大活动地点',
    data_status VARCHAR(16) NOT NULL COMMENT 'OFFICIAL/LEGAL_RULE/DEMO',
    source_name VARCHAR(100) NULL COMMENT '正式数据来源名称',
    source_url VARCHAR(500) NULL COMMENT '正式数据来源链接',
    enabled TINYINT NOT NULL DEFAULT 1 COMMENT '是否参与运行时匹配：1是，0否',
    description VARCHAR(500) NULL COMMENT '维护说明',
    del_flag CHAR(1) NOT NULL DEFAULT 'N' COMMENT '逻辑删除标记：N有效，Y删除',
    create_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间',
    update_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
        ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '最后更新时间',

    PRIMARY KEY (id),
    UNIQUE KEY uk_festival_event_code (event_code),
    KEY idx_festival_active_time (enabled, impact_start_time, impact_end_time),
    KEY idx_festival_region_time (region_code, impact_start_time, impact_end_time),

    CONSTRAINT ck_festival_event_type CHECK (
        event_type IN ('HOLIDAY','ADJUSTED_WORKDAY','CONCERT','SPORTS_EVENT','OTHER_EVENT')
    ),
    CONSTRAINT ck_festival_scope_type CHECK (scope_type IN ('PROVINCE','CITY','ROUTE')),
    CONSTRAINT ck_festival_data_status CHECK (data_status IN ('OFFICIAL','LEGAL_RULE','DEMO')),
    CONSTRAINT ck_festival_enabled CHECK (enabled IN (0,1)),
    CONSTRAINT ck_festival_del_flag CHECK (del_flag IN ('N','Y','0','1')),
    CONSTRAINT ck_festival_event_time CHECK (event_end_time >= event_start_time),
    CONSTRAINT ck_festival_impact_time CHECK (
        impact_start_time <= event_start_time AND impact_end_time >= event_end_time
    ),
    CONSTRAINT ck_festival_route_json CHECK (
        affected_route_codes IS NULL OR JSON_TYPE(affected_route_codes) = 'ARRAY'
    ),
    CONSTRAINT ck_festival_scope_value CHECK (
        (scope_type <> 'CITY' OR region_code IS NOT NULL)
        AND (scope_type <> 'ROUTE' OR JSON_LENGTH(affected_route_codes) > 0)
    )
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci
  COMMENT='福建普通国省干线节假日及重大活动交通背景数据';

